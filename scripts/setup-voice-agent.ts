// Creates (or updates) the CallMentor ElevenLabs agent that uses our mentor as its Custom LLM.
// Usage: npx tsx scripts/setup-voice-agent.ts   (reads .env + .env.local; never prints secrets)
import dotenv from "dotenv";
import { ElevenLabsClient } from "@elevenlabs/elevenlabs-js";

dotenv.config();
dotenv.config({ path: ".env.local" });

const BASE = (process.env.PUBLIC_BASE_URL || "https://callmentor.onrender.com").replace(/\/$/, "");
const SECRET_NAME = "callmentor_voice_llm";
const voiceSecret = process.env.VOICE_LLM_SECRET;
if (!voiceSecret) throw new Error("VOICE_LLM_SECRET missing in .env");

const client = new ElevenLabsClient();

// Workspace secret holding the bearer token ElevenLabs sends to our /v1/chat/completions.
const existing: any = await client.conversationalAi.secrets.list({});
let secretId: string | undefined = (existing.secrets ?? []).find((s: any) => s.name === SECRET_NAME)?.secretId;
if (!secretId) {
  const created: any = await client.conversationalAi.secrets.create({ name: SECRET_NAME, value: voiceSecret });
  secretId = created.secretId;
  console.log("created workspace secret", SECRET_NAME);
} else {
  console.log("reusing workspace secret", SECRET_NAME, "(value not changed)");
}

const conversationConfig: any = {
  agent: {
    firstMessage: "Hi {{learner_name}}! I'm your CallMentor. What would you like to learn or talk through today? You can speak English, Hindi or Hinglish.",
    language: "en",
    dynamicVariables: { dynamicVariablePlaceholders: { learner_name: "there" } },
    prompt: {
      // The real instructions and memory live in our backend (src/mentor.ts); this is a fallback description.
      prompt: "You are CallMentor, a friendly coding mentor. Replies are generated by the CallMentor backend.",
      llm: "custom-llm",
      customLlm: {
        url: `${BASE}/v1/chat/completions`,
        modelId: "callmentor-mentor",
        apiKey: { secretId },
        apiType: "chat_completions",
      },
    },
  },
  tts: { voiceId: "EXAVITQu4vr4xnSDxMaL" },
  asr: { keywords: ["Java", "CallMentor", "equals", "array", "index", "increment", "String"] },
  turn: { turnEagerness: "normal" },
};
const platformSettings: any = { auth: { enableAuth: true } }; // conversations need a signed URL from our server

const agentId = process.env.ELEVENLABS_AGENT_ID;
if (agentId) {
  await client.conversationalAi.agents.update(agentId, { name: "CallMentor Voice", conversationConfig, platformSettings });
  console.log("updated agent", agentId);
} else {
  const a: any = await client.conversationalAi.agents.create({ name: "CallMentor Voice", conversationConfig, platformSettings });
  console.log("created agent", a.agentId, "-> set ELEVENLABS_AGENT_ID to this value");
}
